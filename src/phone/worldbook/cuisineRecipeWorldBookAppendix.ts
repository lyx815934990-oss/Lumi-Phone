1. **融进动作**：夹菜、吹烫、搅拌拉丝芝士、掰开小笼灌汤、涮毛肚数秒、用小勺挖熔岩心、分食同一块蛋糕——少写静态菜单朗读。
2. **两人差异**：口味可不同（一辣一清淡、一肉食一素、一甜口一不爱甜）；抢菜、让菜、让最后一口甜品可服务关系，勿两人同点同评。
3. **仍遵守去废话 / 零比喻硬规则**：写具体菜与滋味，勿「像初恋一样的甜」「舌尖上的爆炸」空比喻。
4. **卫生与常识**：生食、醉蟹、野生菌等须合人设与场合；过敏与忌口不得当情趣强行突破。
5. **词库点缀**：每餐挑少数菜名落地，禁止把整列菜系/甜品抄进正文。

