/**
 * 显式指定关系阶段时拼接：核心层 + 该阶段模块。
 * 日常路径请用 {@link WECHAT_ROLEPLAY_SYSTEM_PROMPT} / {@link buildWeChatCoreOnlyPrompt}。
 * @throws 未知 stage
 */
export function buildWeChatSystemPrompt(stage: RelationshipStage): string {
  const stageModule = RELATIONSHIP_STAGE_MODULES[stage]
  if (!stageModule) {
    throw new Error(`未知的关系阶段: ${stage}，请检查 relationshipStage 的取值是否在枚举范围内`)
  }
  return `${WECHAT_CORE_PROMPT}\n\n${stageModule}`
}

export type InferWeChatRelationshipStageHints = {
  affection?: number | null
  relationshipLabel?: string | null
  relationshipDef?: string | null
  epilogueOrWorldBookSnippet?: string | null
}

/**
 * @deprecated 私聊默认不再自动推断阶段；关系由模型按世界书/尾声自行把握。
 * 仅供调试或外部工具在「显式注入阶段模块」前做粗映射时选用。
 */
export function inferWeChatRelationshipStage(
  hints?: InferWeChatRelationshipStageHints | null,
): RelationshipStage {
  const blob = [
    hints?.relationshipLabel,
    hints?.relationshipDef,
    hints?.epilogueOrWorldBookSnippet,
  ]
    .filter((s): s is string => typeof s === 'string' && s.trim().length > 0)
    .join('\n')

  if (blob) {
    if (/仇恨|敌对|势不两立|仇人|死对头/.test(blob)) return 'hostile'
    if (/冷战|闹僵|冷战中|冷战期/.test(blob)) return 'cold_war'
    if (
      /已确认恋人|已确认情侣|正式交往|男女朋友|是情侣|是恋人|伴侣|在一起了|恋爱中/.test(blob) &&
      !/单相思|暗恋未|未表白/.test(blob)
    ) {
      return 'confirmed_lover'
    }
    if (/暗恋|未表白|藏着喜欢|嘴上不承认/.test(blob)) return 'secret_crush'
    if (/单相思|表白过|已表白|已表达.*未|追求被拒|未被回应/.test(blob)) return 'unrequited_open'
    if (/追求中|公开示好|明确追求|暧昧追求|在追/.test(blob)) return 'active_pursuit'
    if (/陌生|刚认识|客气|礼貌疏离|防备/.test(blob)) return 'stranger_polite'
    if (/略有好感|轻微好感|熟人|朋友/.test(blob)) return 'slight_fondness'
  }

  const a = hints?.affection
  if (typeof a === 'number' && Number.isFinite(a)) {
    if (a < 20) return 'stranger_polite'
    if (a < 60) return 'slight_fondness'
    return 'active_pursuit'
  }

  return 'slight_fondness'
}

