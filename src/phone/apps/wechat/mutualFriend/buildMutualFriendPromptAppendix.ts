import { loadMutualFriendRelayRecords } from './storage'
import type { MutualFriendPeerOption } from './types'

function formatRelayClock(ts: number): string {
  try {
    return new Date(ts).toLocaleTimeString('zh-CN', { hour: '2-digit', minute: '2-digit' })
  } catch {
    return ''
  }
}

/** 注入私聊 system：共同好友链协议 + 触发场景 + 最近传话防重复 */
export function buildMutualFriendChainPromptAppendix(params: {
  currentCharacterId: string
  peers: MutualFriendPeerOption[]
}): string {
  const peers = params.peers.filter((p) => p.characterId.trim())
  if (!peers.length) return ''

  const allowLines = peers.map(
    (p) => `- id=${p.characterId} 名称参考：${p.displayName}`,
  )

  const cid = params.currentCharacterId.trim()
  const recent = loadMutualFriendRelayRecords(cid).slice(-5)
  const nameById = new Map(peers.map((p) => [p.characterId, p.displayName]))
  nameById.set(cid, '你')

  let relayContext = ''
  if (recent.length) {
    const lines = recent.flatMap((r) => {
      const clock = formatRelayClock(r.timestamp)
      const out: string[] = []
      if (r.fromRoleId === cid) {
        const toName = nameById.get(r.toRoleId) || r.toRoleId
        out.push(`【传话记录】你在${clock}向${toName}打听/转达："${r.relayedMessage}"`)
        if (r.heardBack?.trim()) {
          out.push(
            `【已知晓】${toName}已私下告诉你事情经过："${r.heardBack.trim()}" → 后续聊天须体现你已知情，勿再装作不知道、勿再问「谁告诉你的」。`,
          )
        }
      } else {
        const fromName = nameById.get(r.fromRoleId) || r.fromRoleId
        out.push(`【传话记录】${fromName}在${clock}向你打听/转达："${r.relayedMessage}"`)
        if (r.heardBack?.trim()) {
          out.push(
            `【已知晓】你已把经过告诉${fromName}："${r.heardBack.trim()}"（若未写私信块，表示你当时未主动私信玩家）。`,
          )
        }
        out.push(
          `【可对质】若内容像是你的秘密/好感被玩家捅给了${fromName}，后续与玩家聊天可自然怀疑、追问「是不是你告诉他的」；必要时可再出私信块对质（勿无端重复轰炸）。`,
        )
      }
      return out
    })
    relayContext =
      `【传话记录（重要：避免重复传话 / 保持知情）】\n` +
      `${lines.join('\n')}\n` +
      `- 更早轮次已转达或已打听过同一件事 → 直接说「我已经问过了/转达了」，不要再问要不要传；**也不要再输出同一件事的新标记块**。\n` +
      `- **例外·重新回复**：若本轮是「重新回复/重写上一轮 AI 气泡」，同轮旧传话记录会被客户端撤回；须当作**首次作答**。气泡若写「我去问/已甩给他/去打听」等，**必须重新输出完整标记块**，禁止只口头宣称。\n` +
      `- 已有【已知晓】→ 后续须按已知事实接话，禁止装傻重问经过。\n` +
      `- 别人已向你打听/转达 → 勿装作完全不知情；若像是自己的秘密被玩家捅破，可对玩家怀疑对质，但不要反复追问「到底谁告诉你的」那种失忆式台词。\n\n`
  }

  return (
    `${relayContext}` +
    `【共同好友链（联动聊天模式已开启）】\n` +
    `你与下列人脉可互通和用户有关的聊天内容。本轮若发生传话/打听，必须在**可见话术之后、全文最末尾**追加标记块。\n` +
    `**铁律：只在气泡里说「我去问问他/我帮你说一声」却不写标记块 = 系统无法记账与投递，等于没做。**\n` +
    `**禁止 JSON**；只用下面这种多行标记（键值用中文冒号「：」或英文「:」均可）。\n` +
    `\n` +
    `格式示例：\n` +
    `<<MUTUAL_FRIEND_CHAIN>>\n` +
    `传话\n` +
    `id：角色ID\n` +
    `因：一句话原因（弹窗用）\n` +
    `告：你向对方打听或转告的摘要\n` +
    `闻：对方私下告诉你的事情经过（可选）\n` +
    `结束传话\n` +
    `私信\n` +
    `id：角色ID\n` +
    `因：一句话原因（可选）\n` +
    `说：对方发给玩家的第 1 条气泡\n` +
    `说：第 2 条\n` +
    `说：第 3 条\n` +
    `说：……按需要继续「说：」行，勿偷懒只写一两句\n` +
    `结束私信\n` +
    `<<END_MUTUAL_FRIEND_CHAIN>>\n` +
    `\n` +
    `字段说明：\n` +
    `- 可只写「传话」块、只写「私信」块，或两块都写；不需要联动时**不要输出**整段（含起止标记）。\n` +
    `- 「因」：有传话块时建议必填，短中文，如「想确认你说的喜欢的事」。\n` +
    `- 「告」：你向对方说了什么 / 问了什么。\n` +
    `- 「闻」：对方**当场口头回你**的内容（强烈建议填写）。例如你问「小刚怎么没来」，对方回「他生病了，休息一天就好」→ 必须写进「闻」。有答复却不写「闻」= 双方记忆都记不住对方回了什么。\n` +
    `- 「私信」+ 多行「说」：被传话的那个人**主动私信玩家**的气泡（不是写给你看的旁白）。**条数与普通微信回复相同**：一行一条气泡，按对方性格与情绪自然分条（日常宜 6～12 行短句，情绪上来可更多）；**禁止**只写 1～2 条敷衍收工，**禁止**习惯性压到 4～5 条就停，**禁止**自设条数上限。客户端不会截断「说：」行。\n` +
    `- id 只能取自下列名单（禁止编造）：\n` +
    `${allowLines.join('\n')}\n` +
    `\n` +
    `【被传话方是否私信玩家——由模型综合判断（禁止关键词一刀切）】\n` +
    `写完「传话」后，站在**被转告的那个人**的视角，结合下列信息自行决定要不要写「私信」块；**客户端不会按关键词抽签或强制**。\n` +
    `1) **人设**：对方性格会不会主动找人？直球/回避/高冷/黏人/爱面子/怕麻烦等，以档案与世界书为准。\n` +
    `2) **与玩家的关系与阶段**：恋人、暧昧、朋友、死对头、上下级等；当前是热恋、疏远、刚吵完、还是已经在冷战/冷战边缘。\n` +
    `3) **听到转告后的当下动机**：会不会立刻找玩家解释、求饶、对质、甩锅、装死、或只跟你（传话人）说几句就完。\n` +
    `4) **一致性**：若你在可见气泡里已经写「他吓死了/他连发消息求我稳住/他要去找你」等，则**同轮必须写私信块**把对方找玩家的话写出来；只口头描写、不写私信块 = 对方根本没私信过玩家。\n` +
    `5) **可不写私信的合理情况**：对方性格本就不会主动找、或正与玩家冷战故意不理、或内容只是无关痛痒的打听且对方只愿跟你说一声——此时可只写传话+闻，但「闻」里勿写成对方已狂找玩家。\n` +
    `私信语气、长短、是否示弱/硬撑，一律贴被传话方人设与当下关系状态，不要套固定剧本。\n` +
    `\n` +
    `【结果路径（可组合）】\n` +
    `A) 对方主动找玩家：写私信块（可同时有传话+闻）。是否走 A **由人设+关系+状态判断**，不是看见某些字就必须。\n` +
    `B) 对方只告诉你经过、不私信玩家：只写传话+闻；此后你与玩家聊天必须体现已知情。\n` +
    `C) **秘密/好感被捅破后的连锁**：玩家把某人的秘密告诉你 → 你私下找对方确认（传话）→ 若对方会怀疑泄密且其人设会找玩家对质，再写私信；若对方隐忍不发也需在「闻」里写清其真实反应，勿假装已私信。\n` +
    `\n` +
    `【何时必须输出整块】名单中有对应人脉，且出现以下任一情况：\n` +
    `1) 中立转告 / 2) 八卦闲聊 / 3) 告状 / 4) 求情调和\n` +
    `5) **口头承诺传话/去打听**：气泡出现「我去问问他」等 → **同轮必须出标记块**。\n` +
    `6) **捅破秘密 / 情感试探**：玩家说「某某喜欢你」等 → 宜写传话；是否再写私信对质，按对方人设与关系判断。\n` +
    `\n` +
    `【常见组合】\n` +
    `- 「我去问问他怎么回事」→ 传话（告+闻）；是否私信玩家看对方人设与关系。\n` +
    `- 「帮我转告他一句狠话」→ 传话（告+闻）；若对方听完按人设/关系会找玩家，就写私信；若正冷战故意晾着，可不写私信但「闻」要体现其真实态度。\n` +
    `- 玩家说「B 喜欢你」→ 传话问 B；B 是否私信玩家对质，看 B 的人设与当下状态。\n` +
    `\n` +
    `【何时不要输出整块】\n` +
    `- 纯闲聊且不涉及名单中其他人、无传话/打听动机。\n` +
    `- 玩家明确要求保密。\n` +
    `- 更早轮次刚传过/刚问过同一件事（见上方记录）→ 勿重复出块；**重新回复本轮除外**（见上方例外）。\n` +
    `\n` +
    `【文风】可见气泡保持自然微信话术；标记块仅在全文最末尾；气泡中禁止出现标记。\n`
  )
}
