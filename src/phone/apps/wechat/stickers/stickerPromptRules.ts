/** 根据近期已发引用名，约束本轮勿连发同一张 */
export function buildStickerAntiRepeatPromptBlock(recentCharacterRefs: string[]): string {
  const refs = recentCharacterRefs.map((r) => String(r ?? '').trim()).filter(Boolean)
  if (!refs.length) return ''
  const list = refs.map((r) => `- 表情包 ${r}`).join('\n')
  return `
---------------------
【表情包·勿连发同一张（本轮硬约束）】
---------------------
你方**最近几轮**已发过下列引用名（从旧到新）：
${list}
本轮若再发表情包，**必须**从《表情包资源》目录中选**与上表任一条都不同的**引用名；**禁止**逐字相同，也**禁止**仅改标点/空格/同义微调糊弄。
若仍想表达相近情绪，请换**画面不同**的另一张；若无合适新表情，**本轮不要输出** \`表情包\` 行，改用文字即可。
**宁缺毋滥**：不要为了避开重复而随便换一张不贴脸的；贴脸优先于「必须发一条表情」。
`.trim()
}
